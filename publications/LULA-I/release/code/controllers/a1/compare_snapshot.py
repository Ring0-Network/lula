"""Compare the two branches of the LULA I old-snapshot test: branch A loads the live cache file, branch B loads a copy
(vectors/lula1.snapshot0) made before A ran. Output lines are 'rep ns siglen hex'. Writes results/snapshot-branches.md."""
import hashlib
from pathlib import Path

from release_paths import CODE, RELEASE, campaign, results, build
C = campaign('a1', rerun=False)
RESULTS = results('a1')
BUILD = build()
RAW = C / 'raw'
out = ['# LULA I old-snapshot branches (generated by scripts/compare_snapshot.py)', '']
S0, L0 = C / 'vectors' / 'lula1.snapshot0', C / 'vectors' / 'lula1.cache'
if S0.exists() and L0.exists():
    out.append(f'snapshot file SHA-256 {hashlib.sha256(S0.read_bytes()).hexdigest()}')
    out.append(f'live cache  file SHA-256 {hashlib.sha256(L0.read_bytes()).hexdigest()}')
    out.append('')

def load(p):
    d = {}
    for line in p.read_text().splitlines():
        if line.startswith('#'):
            continue
        rep, ns, ln, hx = line.split()
        d[int(rep)] = (int(ns), int(ln), hx)
    return d

for size, a_name, b_name in ((32, 'lula1-snapA-32.txt', 'lula1-snapB-32.txt'), (1024, 'lula1-snapA-1024.txt', 'lula1-snapB-1024.txt')):
    pa, pb = RAW / a_name, RAW / b_name
    if not (pa.exists() and pb.exists()):
        out.append(f'{size} B: missing branch file'); continue
    A, B = load(pa), load(pb)
    common = sorted(set(A) & set(B))
    same = sum(1 for r in common if A[r][2] == B[r][2])
    out.append(f'- message {size} B: branch A signed {len(A)} messages, branch B {len(B)}; overlap {len(common)}; '
               f'byte-identical on overlap: {same}/{len(common)}; B-only messages (fresh in B): {len(set(B) - set(A))}; '
               f'all signatures {sorted({v[1] for v in list(A.values()) + list(B.values())})} B; every signature was verified by the driver.')
    out.append(f'  median sign A {sorted(v[0] for v in A.values())[len(A)//2]/1e6:.3f} ms, B {sorted(v[0] for v in B.values())[len(B)//2]/1e6:.3f} ms')
out += ['', 'Scope: the RA signer takes an immutable reference when signing; it holds no mutable signing state, so equality of the',
        'branches is the expected outcome of an honest implementation. This is not a security test.']
(RESULTS / 'snapshot-branches.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('\n'.join(out))
