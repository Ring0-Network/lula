"""Aggregate raw/*.csv of this campaign into results/summary.csv and results/summary.md.
Per cell (file group) and operation: N, min, median, p95, p99, maximum observed (nearest-rank quantiles), signature bytes.
Files starting with SMOKE, FUNC or containing 'NOT-A-MEASUREMENT' are excluded. Fresh-process runs (one signature per file)
are pooled by their prefix before the last '-<index>'. Maximum is called 'maximum observed latency'."""
import csv, math, re, statistics
from collections import defaultdict
from pathlib import Path

from release_paths import CODE, RELEASE, campaign, results, build
C = campaign('a1', rerun=False)
RESULTS = results('a1')
BUILD = build()
RAW = C / 'raw'

def nearest_rank(v, q):
    s = sorted(v)
    return s[max(0, math.ceil(q * len(s)) - 1)]

def cell_name(stem):
    m = re.match(r'^(.*-32)-(\d+)$', stem)       # pooled fresh-process runs: name-32-<i>
    return m.group(1) if m and ('fresh' in stem) else stem

groups = defaultdict(lambda: defaultdict(list))
sizes = defaultdict(dict)
for f in sorted(RAW.glob('*.csv')):
    if f.name.startswith(('SMOKE', 'FUNC')) or 'NOT-A-MEASUREMENT' in f.name:
        continue
    name = cell_name(f.stem)
    with open(f, encoding='utf-8') as fh:
        for r in csv.DictReader(fh):
            op = r.get('operation')
            ns = r.get('ns')
            if not op or not ns:
                continue
            groups[name][op].append(int(float(ns)))
            sb = r.get('sig_bytes')
            if op in ('sign', 'verify') and sb:
                sizes[name].setdefault(op + '_sig_bytes', set()).add(int(float(sb)))

rows = []
for name in sorted(groups):
    for op in sorted(groups[name]):
        v = groups[name][op]
        sb = sizes[name].get('sign_sig_bytes') or sizes[name].get('verify_sig_bytes') or set()
        zeros = sum(1 for x in v if x == 0)
        rows.append({'cell': name, 'operation': op, 'N': len(v), 'min_ms': min(v) / 1e6,
                     'median_ms': statistics.median(v) / 1e6, 'p95_ms': nearest_rank(v, 0.95) / 1e6,
                     'p99_ms': nearest_rank(v, 0.99) / 1e6, 'max_observed_ms': max(v) / 1e6,
                     'zero_ns_rows': zeros, 'sig_bytes': '/'.join(str(x) for x in sorted(sb))})
out = RESULTS / 'summary.csv'
with open(out, 'w', newline='', encoding='utf-8') as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
    w.writeheader(); w.writerows(rows)
with open(RESULTS / 'summary.md', 'w', encoding='utf-8', newline='\n') as fh:
    fh.write('# Summary (generated by scripts/aggregate.py; times in ms; quantiles nearest-rank; max = maximum observed latency)\n\n')
    fh.write('| cell | op | N | min | median | p95 | p99 | max observed | sig bytes |\n|---|---|---|---|---|---|---|---|---|\n')
    for r in rows:
        if r['operation'] in ('sign', 'verify', 'fixture_load', 'keygen', 'key_restore_and_state_init', 'fixture_load_or_restore'):
            fh.write(f"| {r['cell']} | {r['operation']} | {r['N']} | {r['min_ms']:.4g} | {r['median_ms']:.4g} | {r['p95_ms']:.4g} | {r['p99_ms']:.4g} | {r['max_observed_ms']:.4g} | {r['sig_bytes']} |\n")
print(len(rows), 'rows')
